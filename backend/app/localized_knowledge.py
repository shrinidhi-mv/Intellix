def get_localized_summary(doc_id: str, lang_code: str) -> Optional[str]:
    """
    Retrieves a 100% pure native language summary with zero English mixing.
    Matches filename or stem (e.g. 'irrigation_drip_sprinkler_guide.md' or 'irrigation_drip_sprinkler').
    """
    if not doc_id:
        return None
        
    cleaned_id = doc_id.strip()
    if not cleaned_id.endswith(".md"):
        cleaned_id = cleaned_id + ".md"

    # Direct match
    if cleaned_id in LOCALIZED_KB_SUMMARIES:
        return LOCALIZED_KB_SUMMARIES[cleaned_id].get(lang_code)

    # Stem match
    stem = cleaned_id.replace(".md", "")
    for key, val_dict in LOCALIZED_KB_SUMMARIES.items():
        if stem in key or key.replace(".md", "") in stem:
            return val_dict.get(lang_code)

    return None
